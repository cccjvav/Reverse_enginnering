const generated=await reconstruct({write:false});
const original=await readFile(path.join(ROOT,generated.report.origin),'utf8');

test('reconstruction is deterministic; every original declaration hash and generated byte matches',async()=>{
  const stored=JSON.parse(await readFile(path.join(ROOT,'reconstructed/bridge-core/provenance.json'),'utf8'));
  assert.deepEqual(stored,generated.report);
  assert.deepEqual((await readdir(path.join(ROOT,'reconstructed/bridge-core/src'))).sort(),[...generated.files.keys()].sort());
  for(const m of generated.report.modules){
    const bytes=await readFile(path.join(ROOT,'reconstructed/bridge-core',m.file));assert.equal(hash(bytes),m.sha256);
    for(const d of m.declarations)assert.equal(hash(original.slice(d.start,d.end)),d.originalSha256);
  }
  assert.equal(generated.report.moduleCount,24);
  assert.ok(generated.report.sourceLabelIndex.some(m=>m.headingOffsets.length>1));
});

test('every reconstructed module loads in Node without npm runtime packages',async()=>{
  for(const m of generated.report.modules){
    const loaded=await import(pathToFileURL(path.join(ROOT,'reconstructed/bridge-core',m.file)));
    assert.deepEqual(Object.keys(loaded).sort(),m.exports);
  }
  assert.equal('dispatchFileTool' in fileTools,false);
});

test('scope analysis sees lexical dependencies, not property names or shadowed parameters',()=>{
  assert.deepEqual(scopeInfo('function f(local) { return external.call(local); }').free,['external']);
  assert.deepEqual(scopeInfo('const external = 1; function f() { return external; }').free,[]);
  assert.deepEqual(scopeInfo('const f = () => hidden;').free,['hidden']);
  assert.doesNotThrow(()=>assertOmittableInitializer(scopeInfo('init_define_SHUNCODE_BUILD_INFO();').ast.body[0],'fixture'));
  for(const code of ['state.ready = true;','startServer();','init_define_SHUNCODE_BUILD_INFO(extra);'])assert.throws(()=>assertOmittableInitializer(scopeInfo(code).ast.body[0],'fixture'),/Unmodeled top-level statement/);
});

