test('legacy input normalization is non-mutating and refuses conflicting aliases',()=>{
  const input={path:'src/a.js',start:2,endLine:4};
  assert.deepEqual(compat.normalizeFileToolInput('read_file',input),{files:[{path:'src/a.js',start_line:2,end_line:4}]});
  assert.deepEqual(input,{path:'src/a.js',start:2,endLine:4});
  assert.throws(()=>compat.normalizeFileToolInput('search_files',{query:'one',pattern:'two'}),/conflicting/);
  assert.throws(()=>compat.normalizeFileToolInput('search_files',{paths:['a','b'],pattern:'x'}),/exactly one path/);
});

test('schema validation and tool parsers are separate checks, not a filesystem sandbox',()=>{
  const schema=fileTools.FILE_TOOL_DEFINITIONS.find(t=>t.name==='read_files').inputSchema;
  assert.throws(()=>validateToolInput('read_files',schema,{files:[]}),/INVALID_ARGUMENT/);
  assert.throws(()=>validateToolInput('read_files',schema,{files:[{path:'a'}],unexpected:true}),/INVALID_ARGUMENT/);
  assert.throws(()=>fileTools.parseReadFilesInput({files:[{path:'a',start_line:0}]}),/integer >= 1/);
  assert.equal(fileTools.parseSearchFilesInput({pattern:'needle'}).pattern,'needle');
  // A syntactically valid path is not proof it is within a workspace. That
  // enforcement lives in the not-yet-reconstructed file-operation layer.
  assert.equal(fileTools.parseReadFilesInput({files:[{path:'../outside'}]}).files[0].path,'../outside');
});

test('isolated original declarations and ESM reconstruction agree on deterministic parser cases',()=>{
  // Execute ONLY the hash-checked, reviewed declaration closure, never the full
  // extension bundle. VM is a comparison harness, not a security sandbox.
  const declarations=generated.report.modules.flatMap(m=>m.declarations).sort((a,b)=>a.start-b.start);
  const baselineSource=declarations.map(d=>d.snapshotMetadataAssignment?`const ${d.names[0]} = ${original.slice(d.start,d.end)};`:original.slice(d.start,d.end)).join('\n');
  const require=createRequire(import.meta.url);
  const baseline=vm.runInNewContext(baselineSource+'\n({normalizeFileToolInput,parseReadFilesInput,parseSearchFilesInput,validateToolInput,FILE_TOOL_DEFINITIONS})',{
    require:specifier=>{assert.equal(specifier,'node:crypto');return require(specifier);},Buffer,setTimeout,clearTimeout,
  },{timeout:1000});
  const canonical=fn=>{try{return JSON.stringify({result:fn()});}catch(e){return JSON.stringify({error:e.message});}};
  const cases=[{},null,{path:'a',start:2},{files:['a']},{files:[]},{files:[{path:'a',start_line:0}]},{query:'a',pattern:'b'}];
  for(const input of cases){
    for(const tool of ['read_files','search_files'])assert.equal(canonical(()=>compat.normalizeFileToolInput(tool,input)),canonical(()=>baseline.normalizeFileToolInput(tool,input)));
    for(const name of ['parseReadFilesInput','parseSearchFilesInput'])assert.equal(canonical(()=>fileTools[name](input)),canonical(()=>baseline[name](input)));
  }
  assert.equal(JSON.stringify(fileTools.FILE_TOOL_DEFINITIONS),JSON.stringify(baseline.FILE_TOOL_DEFINITIONS));
});

test('community candidate fixes shrinking admission without revoking in-flight work',async()=>{
  const s=new CommunitySemaphore(3),a=await s.acquire(),b=await s.acquire(),c=await s.acquire();
  let admitted=false;const waiting=s.acquire().then(release=>{admitted=true;return release;});
  s.setLimit(1);a();await Promise.resolve();assert.equal(admitted,false);assert.equal(s.active,2);
  b();await Promise.resolve();assert.equal(admitted,false);assert.equal(s.active,1);
  c();const release=await waiting;assert.equal(admitted,true);assert.equal(s.active,1);release();assert.equal(s.active,0);
});

